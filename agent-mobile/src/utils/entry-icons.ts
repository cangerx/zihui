/** 双色实心入口图标 → data URI */
export function entryIcon(name: string, color: string): string {
  const def = ENTRIES[name]
  if (!def) return ''
  const tint = def.tint ? `<path d="${def.tint}" fill="${color}" fill-opacity="0.26"/>` : ''
  const main = `<path d="${def.main}" fill="${color}"/>`
  return svgToDataUri(
    `<svg xmlns="http://www.w3.org/2000/svg" width="72" height="72" viewBox="0 0 24 24">${tint}${main}</svg>`,
  )
}

export function hasEntryIcon(name: string): boolean {
  return Boolean(ENTRIES[name])
}
